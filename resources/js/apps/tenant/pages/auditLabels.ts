export function auditGroupOf(action: string) {
    return auditGroups.find((g) => g.prefixes.some((p) => action.startsWith(p))) ?? auditGroups[5];
}

/** Action in words, falling back to the last part of the code when an action has no label yet. */
export function auditLabel(action: string): string {
    return auditLabels[action] ?? action.replace(/[._]/g, ' ');
}
